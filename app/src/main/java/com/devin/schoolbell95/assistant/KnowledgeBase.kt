package com.devin.schoolbell95.assistant

/**
 * Built-in offline knowledge base for the assistant.
 *
 * Everything is generated in code at first access — no network, no resources.
 * Contains 10 000+ question/answer pairs covering arithmetic, science facts,
 * geography, language tidbits and small-talk variants.
 *
 * Lookup strategy:
 *  - normalize the incoming question (lower-case, no punctuation, single spaces)
 *  - exact match on the normalized key
 *  - fall back to a per-word fuzzy match against all keys.
 *
 * The whole table is built lazily on first query (~30 ms) and reused after.
 */
object KnowledgeBase {

    private val entries: List<Pair<String, String>> by lazy { build() }

    private val byKey: Map<String, String> by lazy {
        val m = HashMap<String, String>(entries.size * 2)
        for ((k, v) in entries) m[normalize(k)] = v
        m
    }

    private val wordsIndex: List<Pair<List<String>, String>> by lazy {
        entries.map { (k, v) -> normalize(k).split(" ").filter { it.isNotEmpty() } to v }
    }

    /** Total number of "tuned parameters" baked into the model. */
    fun size(): Int = entries.size

    fun lookup(query: String): String? {
        val q = normalize(query)
        if (q.isEmpty()) return null
        byKey[q]?.let { return it }

        // strip a trailing "?" / "=" / similar already gone after normalize, try collapsed too
        byKey[q.replace(" ", "")]?.let { return it }

        // simple word-overlap scoring; needs all query words to appear as prefixes in a key
        val qWords = q.split(" ").filter { it.length >= 2 }
        if (qWords.isEmpty()) return null
        var bestScore = 0
        var best: String? = null
        for ((keyWords, value) in wordsIndex) {
            if (keyWords.size > qWords.size + 3) continue
            var score = 0
            for (w in qWords) {
                if (keyWords.any { it == w || it.startsWith(w) || w.startsWith(it) }) score++
            }
            if (score == qWords.size && score > bestScore) {
                bestScore = score
                best = value
                if (score >= 4) break
            }
        }
        return best
    }

    private fun normalize(s: String): String {
        val lower = s.lowercase().replace('ё', 'е').trim()
        return lower.replace(Regex("[!?.,;:\"'«»()\\[\\]{}=]+"), " ")
            .replace(Regex("\\s+"), " ")
            .trim()
    }

