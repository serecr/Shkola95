    private fun sieve(limit: Int): Set<Int> {
        val mark = BooleanArray(limit + 1)
        val res = mutableSetOf<Int>()
        for (i in 2..limit) {
            if (!mark[i]) {
                res.add(i)
                var j = i.toLong() * i
                while (j <= limit) {
                    mark[j.toInt()] = true
                    j += i
                }
            }
        }
        return res
    }
