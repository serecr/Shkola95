        addPeriodicTable(out)
        addRussiaFacts(out)
        addLanguageFacts(out)
        addSchoolFacts(out)
        addSmalltalkVariants(out)
        addFunFacts(out)

        return out
    }

    // 1) Arithmetic — multiplication / addition / subtraction / division with multiple phrasings.
    private fun addArithmetic(out: MutableList<Pair<String, String>>) {
        val mulForms = listOf("%d*%d", "%d умножить на %d", "%d на %d", "сколько %d на %d", "произведение %d и %d")
        val addForms = listOf("%d+%d", "%d плюс %d", "сумма %d и %d", "сколько %d плюс %d", "сложить %d и %d")
        val subForms = listOf("%d-%d", "%d минус %d", "разность %d и %d", "сколько %d минус %d", "отнять %d от %d")
        val divForms = listOf("%d/%d", "%d разделить на %d", "%d делить на %d", "сколько %d разделить на %d")

        for (a in 1..20) for (b in 1..20) {
            val ab = a * b
            for (f in mulForms) out.add(f.format(a, b) to "$ab")
        }
        // 20*20*5 = 2000

        for (a in 1..30) for (b in 1..30) {
            val ab = a + b
            for (f in addForms) out.add(f.format(a, b) to "$ab")
        }
        // 30*30*5 = 4500

        for (a in 1..30) for (b in 1..30) {
            if (a >= b) {
                val ab = a - b
                for (f in subForms) out.add(f.format(a, b) to "$ab")
            }
        }
        // ~ 465 * 5 = 2325

        for (a in 2..12) for (b in 1..12) {
            val p = a * b
            for (f in divForms) out.add(f.format(p, a) to "$b")
        }
        // 11*12*4 = 528
    }

